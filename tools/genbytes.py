#!/usr/bin/env python3
"""Generate src/kpphot/hot_bytes.h: the exact code bytes each kpphot patch depends on, taken from YOUR OWN device's
libs (copied from your Kindle into a private directory). The generated header contains firmware bytes: never commit
or publish it (it is in .gitignore). usage: python3 -I tools/genbytes.py SYMDIR OUT/hot_bytes.h      (write the header, keep it outside the repo)
       python3 -I tools/genbytes.py --hash SYMDIR               (hash-only check, writes nothing)"""
import hashlib, os, sys

# name, lib file, start, end (end exclusive)
REGIONS = [
    # KUX selection (main executable KPPMainAppV2 of FW 5.18.2; ET_EXEC, vaddr = file offset + 0x10000)
    ("kpp_edge", "KPPMainAppV2", 0xd91494, 0xd914c4),      # getInitialUnpopulatedLayoutSettings: mov.w r3,#1000; str [r1,#0x198]
    ("kpp_thr_fn", "KPPMainAppV2", 0xf5d890, 0xf5d8e4),    # SelectionManager notify throttle fn + literals (1e6, 300e6 ns)
    ("kpp_thr_rsb", "KPPMainAppV2", 0xf5fef0, 0xf5ff04),   # updateSelection deferred re-notify: rsbs r2,r2,#300
    ("kpp_repeat", "KPPMainAppV2", 0x15461d0, 0x15461e8),  # rodata int64 1000 ms (edge repeat after a transition)
    ("kpp_onpan", "KPPMainAppV2", 0xf73fc8, 0xf7401c),     # DefaultSelectionEventHandler::onPanEvent body
    ("gdk_gray8", "libgdk-x11-2.0.so.0.2000.1", 0x29538, 0x295b8),   # gdk_rgb_convert_gray8 (static)
    ("cairo_getimg", "libcairo.so.2.11000.0", 0x5d840, 0x5e040),     # _get_image_surface (static), whole function
    ("x11_getpixel8", "libX11.so.6.3.0", 0x20870, 0x208fc),          # _XGetPixel8 (static)
    ("imgu_lanczos", "libImageUtils.so", 0xd200, 0xd280),            # Lanczos kernel calling sin@plt
    ("rn_lz4", "libReactNative.so", 0x1e3508, 0x1e4290),           # LZ4_compress_fast_extState .. LZ4_compress_default (Thumb)
    ("pix_div", "libpixman-1.so.0.18.4", 0x41040, 0x41210),          # static libgcc __udivsi3/__divsi3/__aeabi_idivmod
    ("pix_ldiv", "libpixman-1.so.0.18.4", 0x412fc, 0x418c0),         # static libgcc 64-bit division (__aeabi_ldivmod 0x415bc ..)
]
def fnv64(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h


if len(sys.argv) == 3 and sys.argv[1] == "--hash":
    # Hash-only variant: prints the sha256 + size of each binary and the FNV-1a-64 of each region. No firmware bytes
    # are written anywhere. Use it to confirm your device has exactly the binaries the patches were written for.
    symdir = sys.argv[2]
    for name, lib, a, b in REGIONS:
        data = open(os.path.join(symdir, lib), "rb").read()
        print(f"{name:14} {lib:28} sha256 {hashlib.sha256(data).hexdigest()} size {len(data)} "
              f"region 0x{a:x}+{b - a} fnv64 0x{fnv64(data[a:b]):016x}")
    sys.exit(0)
if len(sys.argv) != 3:
    sys.exit(__doc__)
symdir, out = sys.argv[1], sys.argv[2]
o = ["/* generated by tools/genbytes.py from the device libs; do not edit */", "#include <stdint.h>"]
for name, lib, a, b in REGIONS:
    data = open(os.path.join(symdir, lib), "rb").read()
    o.append(f"/* {lib} sha256 {hashlib.sha256(data).hexdigest()} size {len(data)} */")
    o.append(f"#define {name.upper()}_FSIZE {len(data)}")
    o.append(f"#define {name.upper()}_OFF 0x{a:x}")
    o.append(f"#define {name.upper()}_LEN {b - a}")
    chunk = data[a:b]
    o.append(f"static const uint8_t {name}_bytes[{b - a}] = {{")
    for i in range(0, len(chunk), 16):
        o.append("  " + ", ".join(f"0x{x:02x}" for x in chunk[i:i + 16]) + ",")
    o.append("};")
open(out, "w").write("\n".join(o) + "\n")
print("wrote", out)
