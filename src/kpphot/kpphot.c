/* libkpphot.so - runtime hot patches for static (non-interposable) hot loops in KPPMainApp's libraries
 * (Kindle Oasis 3, FW 5.18.2). LD_PRELOAD library; every patch has its own env switch, default off.
 *
 * Framework: in the constructor (all DT_NEEDED libraries are mapped and relocated, no other thread has run any of
 * their code yet) each enabled patch
 *   1. finds its library with dl_iterate_phdr (basename match), checks the file size (stat of the mapped path) and
 *      compares the EXACT in-memory bytes of every code region the patch depends on with the bytes taken from the
 *      device's own copy (src/hot_bytes.h, generated by tools/genbytes.py; libs have no TEXTREL, so memory == file);
 *   2. writes an absolute jump (ARM `ldr pc, [pc, #-4]; .word target`) over a site that is not a branch target,
 *      with mprotect(RWX) on the page(s), __builtin___clear_cache, then mprotect back to R+X.
 * Any mismatch -> that patch is skipped and the original code runs. Kill switch /mnt/us/DISABLE_KPPFAST.
 *
 * Patches
 *   KPPHOT_GDKGRAY=1  libgdk 2.20 gdk_rgb_convert_gray8 (static, 0x29538; reached through image_info->conv from
 *                     gdk_draw_pixbuf / gdk_draw_rgb_image on the 8-bit StaticGray visual): whole-function
 *                     replacement, out = (g + ((r + b) >> 1)) >> 1 as two NEON vhadd (exact), scalar tail.
 *   KPPHOT_CAIROGET=1 libcairo 1.10 _get_image_surface (static, 0x5d840): the per-pixel XImage -> RGB24 loop of
 *                     the non-TrueColor branch (visual_info != NULL): XGetPixel through ximage->f.get_pixel +
 *                     visual_info->colors[p & 0xff] -> r<<16|g<<8|b. Patched at 0x5debc (just before the loop,
 *                     not a branch target); the stub runs the loop in C when ximage is ZPixmap/8 bpp/depth 8 and its
 *                     get_pixel is libX11's _XGetPixel8 (then get_pixel(x,y) == data[y*bpl+x], proven from the
 *                     disassembly), and jumps to the loop exit 0x5de2c with the same live state; otherwise it
 *                     replays the two overwritten instructions and continues in the original loop (0x5dec4).
 *                     =2: verify mode - every fast result is compared with the original per-pixel calls.
 * Reader patches (main executable KPPMainAppV2 v32 = sha256 c685dd53..., ET_EXEC Thumb-2; the whole
 * 0x30..0x54-byte region around every site is compared with the device's own file before anything is written):
 *   KPPHOT_RSEL_EDGE=ms     KUX hold time at the page edge before the page turns while dragging a selection
 *                           (yj::LayoutSettings+0x198, set once in KUXRenderingInterface::getInitialUnpopulatedLayout-
 *                           Settings: `mov.w r3,#1000` at 0xda14ac becomes `movw r3,#ms`). 100..2000.
 *   KPPHOT_RSEL_THROTTLE=ms kux::SelectionManager notifies selectionChanged (UI redraw + edge check) at most every
 *                           300 ms: literal 300000000 ns at 0xf6d8e0 and `rsbs r2,r2,#300` at 0xf6fefa. 50..255.
 *   KPPHOT_RSEL_REPEAT=ms   hold before the NEXT turn when the finger stays at the edge after a turn (int64 1000 at
 *                           0x15561d8, SelectionViewController event 0x403). 100..5000.
 *   KPPHOT_RSEL_PANFIX=1    EXPERIMENT: DefaultSelectionEventHandler::onPanEvent finalizes instead of updating when
 *                           the selection is already "stabilized" (cbnz at 0xf83fd4 -> nop: always update).
 * Diagnostics: KPPHOT_LOG=path (status lines + counters, every 512th call).
 */
